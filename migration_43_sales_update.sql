-- 매출 수정(담당자/항목/금액 등) 허용
-- "매출은 다 잡아놨는데 트레이너 실적에 안 잡힌다"는 문의를 조사하다가, 매출입력 화면에 "삭제"만
-- 있고 "수정"은 아예 없어서(등록할 때 담당자/항목을 잘못 골라도 고칠 방법이 없음) 실제로 겪으신
-- 문제였음을 확인함. 매출 삭제(migration_15)와 같은 이유로, 수정도 지점장만 할 수 있게 제한함
-- (트레이너가 남의 매출까지 마음대로 고칠 수 있으면 안 되니까).
create policy "매출 수정" on sales for update using (is_manager()) with check (is_manager());
