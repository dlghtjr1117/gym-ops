-- "이용권 판매(등록)"에서 항목별로 지정하는 "시작일"(이용권이 실제로 언제부터 유효한지)을
-- sales 테이블에도 그대로 저장해두기 위한 컬럼.
--
-- 원래 회원 상세의 "이용권" 탭(보유 이용권 카드)은 이 값을 따로 저장하는 곳이 없어서, 매출 내역 중
-- 해당 종류로 가장 최근에 결제한 매출의 sale_date(판매/결제일)를 "근사 시작일"로 보여주고 있었음.
-- "판매 날짜"(매출로 잡히는 날짜)를 항목별 시작일과 분리하는 기능을 추가하면서, 이 근사가 더 이상
-- 맞지 않게 됨(정산 때 판매 날짜만 따로 바꾸면, 실제 시작일과 무관하게 판매 날짜가 "시작일"인 것처럼
-- 보이는 문제). 그래서 실제 시작일을 sales.item_start_date에 정확히 남겨두고, "이용권" 탭은 이제
-- sale_date 대신 이 값을 우선 사용하도록 코드를 같이 고쳤음(이 컬럼이 없는 예전 매출 건은 지금까지처럼
-- sale_date로 근사).
alter table sales add column if not exists item_start_date date;
